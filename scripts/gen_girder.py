"""Export the ordinary girder sprite from the SS14 entity used by the construction graph."""
import json
import sys
from pathlib import Path
from ss14yaml import Loader
import yaml

root = Path(sys.argv[1])
entities = yaml.load((root / 'Resources/Prototypes/Entities/Structures/Walls/girders.yml').read_text(encoding='utf-8'), Loader=Loader)
girder = next(entity for entity in entities if entity.get('id') == 'Girder')
sprite = next(c for c in girder['components'] if c['type'] == 'Sprite')
sheets = yaml.load((root / 'Resources/Prototypes/Entities/Objects/Materials/Sheets/metal.yml').read_text(encoding='utf-8'), Loader=Loader)
single = next(e for e in sheets if e.get("id") == "SheetSteel1")
state = next(c["state"] for c in single["components"] if c["type"] == "Sprite")
output = """// Generated by scripts/gen_girder.py from the SS14 Girder entity.
[(id: "Girder", name: Some(%s), components: {"Sprite": (sprite: %s, state: %s)}),
(id: "SheetSteel1", parents:["SheetSteel"], components:{"Sprite":(sprite:"Objects/Materials/Sheets/metal.rsi", state:%s), "Stack":(stackType:"Steel",count:1)})]
""" % tuple(map(json.dumps, [girder['name'], sprite['sprite'], sprite['state'],state]))
reinforced = next(e for e in entities if e.get("id") == "ReinforcedGirder")
look = next(c for c in reinforced["components"] if c["type"] == "Sprite")
plate = next(e for e in sheets if e.get("id") == "SheetPlasteel1")
plate_sprite = next(c["state"] for c in plate["components"] if c["type"] == "Sprite")
extra = [
    '(id:"ReinforcedGirder",name:Some(%s),components:{"Sprite":(sprite:%s,state:%s)})'
    % tuple(map(json.dumps,[reinforced["name"],look["sprite"],look["state"]])),
    '(id:"SheetPlasteel1",parents:["SheetPlasteel"],components:{"Sprite":(sprite:"Objects/Materials/Sheets/metal.rsi",state:%s)})'
    % json.dumps(plate_sprite),
]
output = output.rstrip()[:-1] + ',\n' + ',\n'.join(extra) + ']\n'
(Path(__file__).resolve().parents[1] / 'content/prototypes/girder.ron').write_text(output, encoding='utf-8')
