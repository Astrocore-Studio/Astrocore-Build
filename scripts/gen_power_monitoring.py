#!/usr/bin/env python3
"""Export SS14 power-monitoring metadata for entities already present in Build.

Usage: python scripts/gen_power_monitoring.py <SS14>
The output is separate from existing entity prototypes so their simulation data
is not replaced by a different source snapshot during this import.
"""
import argparse
import json
import re
from pathlib import Path

from audit_saltern import git_head
from ss14yaml import Protos


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    args = parser.parse_args()
    build = Path(__file__).resolve().parent.parent
    source = args.source.resolve()
    protos = Protos(source.as_posix())
    known = set()
    for path in (build / 'content/prototypes').glob('*.ron'):
        known.update(re.findall(r'\(id:\s*"([^\"]+)"', path.read_text(encoding='utf-8')))
    consoles, devices = [], []
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    for ident in sorted(known):
        if not protos.get('entity', ident):
            continue
        components = protos.entity_components(ident)
        if 'PowerMonitoringConsole' in components:
            consoles.append(quote(ident))
        spec = components.get('PowerMonitoringDevice')
        if spec is None:
            continue
        if spec.get('group') not in ('Generator', 'SMES', 'Substation', 'APC', 'Consumer'):
            raise ValueError(f'{ident}: invalid monitoring group {spec.get("group")}')
        fields = {
            'prototype': ident,
            'name': protos.entity_name(ident) or ident,
            'group': spec['group'],
            'sourceNode': spec.get('sourceNode', ''),
            'loadNode': spec.get('loadNode', ''),
            'collection': spec.get('collectionName', ''),
            'sprite': spec.get('sprite', ''),
            'state': spec.get('state', ''),
        }
        devices.append('            (' + ', '.join(f'{k}: {quote(v)}' for k, v in fields.items()) + '),')
    output = [
        '// Generated by scripts/gen_power_monitoring.py; do not edit.',
        f'// SS14 revision: {git_head(source)}',
        '[',
        '    (id: "PowerMonitoringData", abstract: true, components: {',
        '        "PowerMonitoring": (',
        '            consoles: [' + ', '.join(consoles) + '],',
        '            devices: [',
        *devices,
        '            ],',
        '        ),',
        '    }),',
        ']',
    ]
    path = build / 'content/prototypes/power_monitoring.ron'
    path.write_text('\n'.join(output) + '\n', encoding='utf-8')
    print(f'{len(consoles)} console types, {len(devices)} monitored device types -> {path}')


if __name__ == '__main__':
    main()
