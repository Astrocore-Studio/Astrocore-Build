#!/usr/bin/env python3
"""Prepare an isolated Cargo launcher for the sibling Engine checkout.

The generated manifest and lockfile live in .local/dev. The tracked Build
manifest and Cargo.lock keep their pinned Git dependencies unchanged.
"""
import argparse
import json
import shutil
import tomllib
from pathlib import Path


def toml(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, list):
        return '[' + ', '.join(toml(item) for item in value) + ']'
    if isinstance(value, dict):
        return '{ ' + ', '.join(f'{key} = {toml(item)}' for key, item in value.items()) + ' }'
    return str(value)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--engine', type=Path)
    parser.add_argument('--refresh-lock', action='store_true',
                        help='Reseed only the generated local lock from Build after dependency changes.')
    args = parser.parse_args()
    build = Path(__file__).resolve().parent.parent
    engine = (args.engine or build.parent / 'Astrocore-Engine').resolve()
    build_manifest = tomllib.loads((build / 'Cargo.toml').read_text(encoding='utf-8'))
    engine_manifest = tomllib.loads((engine / 'Cargo.toml').read_text(encoding='utf-8'))
    locked = tomllib.loads((build / 'Cargo.lock').read_text(encoding='utf-8'))
    source = 'https://github.com/Astrocore-Studio/Astrocore-Engine'
    used = {item['name'] for item in locked['package'] if item.get('source', '').startswith('git+' + source)}
    packages = {}
    for member in engine_manifest['workspace']['members']:
        path = engine / member
        name = tomllib.loads((path / 'Cargo.toml').read_text(encoding='utf-8'))['package']['name']
        packages[name] = path
    missing = used - packages.keys()
    if missing:
        raise ValueError(f'Engine checkout is missing packages: {sorted(missing)}')
    dependencies = dict(build_manifest['workspace']['dependencies'])
    for name, value in list(dependencies.items()):
        if isinstance(value, dict) and value.get('git') == source:
            dependencies[name] = {'path': packages[name].as_posix()}
        elif isinstance(value, dict) and 'path' in value:
            dependencies[name] = {**value, 'path': (build / value['path']).as_posix()}
    dependencies['client'] = {'path': (build / 'apps/client').as_posix()}
    dependencies['tools'] = {'path': (build / 'crates/tools').as_posix()}
    dependencies['astrocore-client'] = {'path': packages['astrocore-client'].as_posix()}
    lines = ['# Generated by scripts/prepare_local_engine.py; local development only.',
             '[package]', 'name = "astrocore-local-runner"', 'version = "0.0.0"',
             'edition = "2024"', 'publish = false', '', '[workspace]', 'resolver = "3"',
             '', '[dependencies]']
    lines += [f'{name} = {toml(value)}' for name, value in sorted(dependencies.items())]
    for name, file in [('client', 'apps/client/src/main.rs'), ('server', 'apps/server/src/main.rs'),
                       ('import-map', 'crates/tools/src/bin/import-map.rs'),
                       ('sync-sprites', 'crates/tools/src/bin/sync-sprites.rs')]:
        lines += ['', '[[bin]]', f'name = {toml(name)}', f'path = {toml((build / file).as_posix())}']
    lines += ['', f'[patch.{toml(source)}]']
    lines += [f'{name} = {{ path = {toml(packages[name].as_posix())} }}' for name in sorted(used)]
    destination = build / '.local/dev'
    destination.mkdir(parents=True, exist_ok=True)
    manifest = destination / 'Cargo.toml'
    text = '\n'.join(lines) + '\n'
    if not manifest.exists() or manifest.read_text(encoding='utf-8') != text:
        manifest.write_text(text, encoding='utf-8', newline='\n')
    if args.refresh_lock and (destination / 'Cargo.lock').exists():
        backup = destination / 'Cargo.lock.before-refresh'
        if not backup.exists():
            shutil.copyfile(destination / 'Cargo.lock', backup)
    if args.refresh_lock or not (destination / 'Cargo.lock').exists():
        shutil.copyfile(build / 'Cargo.lock', destination / 'Cargo.lock')
    print(manifest)


if __name__ == '__main__':
    main()
